-- One phone number, one login, per academy (hardening plan §26).
--
-- Two uniqueness rules disagreed. This table allowed one phone per BRANCH
-- (unique branch_id + phone_number); the platform's login index allows one phone
-- per ACADEMY (unique phone_number + tenant_id). Creating a second user with the
-- same phone in another branch was accepted here, and the login-index upsert then
-- re-pointed the first user's login at the second one: user one, typing their own
-- correct password, got 401. Reproduced; nothing raised an error at any point.
--
-- Numbers were also stored exactly as typed, so "010 1234 5678" and "01012345678"
-- were different strings, and no uniqueness rule could see they were one number.
--
-- This migration:
--   1. drops the per-branch rule (generated by Prisma);
--   2. rewrites stored numbers into the one form the app now writes and looks up
--      (src/lib/phone.ts);
--   3. refuses to continue if two ACTIVE accounts now share a number, rather than
--      deciding which person keeps their login;
--   4. adds the academy-wide rule: at most one ACTIVE account per phone number.
--      Inactive accounts are history and take no part, exactly like the login
--      index, which holds active accounts only.
--
-- Prisma cannot express a partial index in schema.prisma, so step 4 lives only
-- here. Like trainee_subscriptions_one_active_per_trainee, it is invisible to
-- `prisma migrate diff`, so a later `migrate dev` will not generate a DROP for it.

-- 1. (Generated by Prisma.)
DROP INDEX "users_branch_id_phone_number_key";

-- 2. Keep this function identical to normalizePhone in src/lib/phone.ts, and to
-- its copy in prisma/platform/migrations/20261017000000_normalize_phone_numbers.
-- tests/integration/phone-normalization-sql.test.ts runs both copies against the
-- TypeScript version. pg_temp: it lasts only as long as this migration's session.
CREATE OR REPLACE FUNCTION pg_temp.normalize_phone(raw text) RETURNS text
LANGUAGE plpgsql IMMUTABLE AS $fn$
DECLARE
  p text;
BEGIN
  IF raw IS NULL THEN
    RETURN NULL;
  END IF;
  -- Arabic-Indic and Persian digits to ASCII, full-width plus to "+".
  p := translate(raw,
    U&'\0660\0661\0662\0663\0664\0665\0666\0667\0668\0669\06F0\06F1\06F2\06F3\06F4\06F5\06F6\06F7\06F8\06F9\FF0B',
    '01234567890123456789+');
  -- Invisible marks, spaces of every kind, dashes, dots and brackets.
  p := regexp_replace(p,
    '[\u0009-\u000D    -‏ -  ⁦-⁩　﻿().-]',
    '', 'g');
  -- 00 is the international call prefix.
  IF left(p, 2) = '00' THEN
    p := '+' || substr(p, 3);
  END IF;
  -- Egyptian mobiles, in every spelling, become +201x...
  IF p ~ '^01[0125][0-9]{8}$' THEN
    RETURN '+20' || substr(p, 2);
  ELSIF p ~ '^201[0125][0-9]{8}$' THEN
    RETURN '+' || p;
  ELSIF p ~ '^\+2001[0125][0-9]{8}$' THEN
    RETURN '+20' || substr(p, 5);
  END IF;
  RETURN p;
END;
$fn$;

UPDATE "users"
SET "phone_number" = pg_temp.normalize_phone("phone_number")
WHERE "phone_number" IS DISTINCT FROM pg_temp.normalize_phone("phone_number");

-- 3. Two active accounts with one number cannot both keep their login. Which one
-- should is a decision about real people, not a migration's to make.
DO $$
DECLARE
  offenders integer;
BEGIN
  SELECT COUNT(*) INTO offenders
  FROM (
    SELECT "phone_number"
    FROM "users"
    WHERE "is_active"
    GROUP BY "phone_number"
    HAVING COUNT(*) > 1
  ) duplicated;

  IF offenders > 0 THEN
    RAISE EXCEPTION
      'Cannot enforce one active account per phone number: % number(s) belong to more than one active account. '
      'Decide which account keeps each number (deactivate the other or give it its own number), then re-run. '
      'Find them with: SELECT phone_number, COUNT(*) FROM users WHERE is_active '
      'GROUP BY phone_number HAVING COUNT(*) > 1;',
      offenders;
  END IF;
END $$;

-- 4. The rule itself.
CREATE UNIQUE INDEX "users_one_active_account_per_phone"
  ON "users" ("phone_number")
  WHERE "is_active";
